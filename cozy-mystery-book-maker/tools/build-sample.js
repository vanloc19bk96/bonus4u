/*
 * Packs the sample book (tools/sample-src) into js/data/sample.js.
 * The sample is stored as the raw "AI answers" so it goes through the same import path as real answers.
 * Usage: node tools/build-sample.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const SRC = path.join(__dirname, 'sample-src');
const plan = fs.readFileSync(path.join(SRC, 'plan.json'), 'utf8');
const batches = [1, 2, 3, 4, 5].map(i => fs.readFileSync(path.join(SRC, 'chapters-0' + i + '.json'), 'utf8'));
batches.forEach((b, i) => JSON.parse(b)); // fail early on a broken file
JSON.parse(plan);
const out = '/* Generated by tools/build-sample.js from tools/sample-src. A complete 50-chapter sample book. */\n' +
  'window.COZY_SAMPLE = ' + JSON.stringify({
    seed: 'sample-crumb-of-suspicion',
    setup: { penName: 'Sample Author', theme: 'Bakery', chapters: 50, wordsPerPuzzle: 12, gridSize: 13, difficulty: 'medium', year: 2026 },
    planText: plan,
    batchText: batches
  }) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'js', 'data', 'sample.js'), out);
console.log('Wrote js/data/sample.js (' + Math.round(out.length / 1024) + ' KB)');
