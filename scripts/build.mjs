#!/usr/bin/env node
// Builds dist/ for Cloudflare: the hub page from site/ plus one folder per app
// listed in apps.json, served at https://<domain>/<slug>/.
//
// Zero dependencies. Run with `npm run build`.

import {
  copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync,
  renameSync, rmSync, statSync, writeFileSync,
} from 'node:fs';
import { dirname, extname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const APPS = join(ROOT, 'apps');
const SITE = join(ROOT, 'site');
const DIST = join(ROOT, 'dist');
const MAX_ASSET_BYTES = 25 * 1024 * 1024; // Cloudflare limit per static asset

// Dev-only files that must never be published: sources, tests, build tooling,
// buyer notes. Licence files such as OFL.txt are kept.
const SKIP_DIRS = new Set(['node_modules', 'tests', 'test', 'tools', 'scripts', 'src', 'examples']);
const SKIP_FILES = [
  /^\./,
  /^how to use\.(txt|md)$/i,
  /^readme\b/i,
  /\.md$/i,
  /^package(-lock)?\.json$/i,
  /^build[\w.-]*\.js$/i,
  /\.source\.html$/i,
  /\.(mp4|mov|zip|log)$/i,
  /^(thumbs\.db|desktop\.ini)$/i,
];

const SLUG = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const errors = [];
const warnings = [];
const redirects = [];
const report = [];

const config = JSON.parse(readFileSync(join(ROOT, 'apps.json'), 'utf8'));

rmSync(DIST, { recursive: true, force: true });
copyTree(SITE, DIST);

const seen = new Set();
for (const app of config.apps) {
  const { slug } = app;
  if (!SLUG.test(slug ?? '')) { errors.push(`"${slug}": slug must be lowercase kebab-case`); continue; }
  if (seen.has(slug)) { errors.push(`${slug}: listed twice in apps.json`); continue; }
  seen.add(slug);

  const src = join(APPS, slug);
  if (!existsSync(src)) { errors.push(`${slug}: folder apps/${slug} not found`); continue; }

  const out = join(DIST, slug);
  const stats = copyTree(src, out);
  report.push({ url: `/${slug}/`, ...stats });

  if (app.tools) {
    for (const tool of app.tools) {
      const target = join(out, tool.path, tool.path.endsWith('.html') ? '' : 'index.html');
      if (!existsSync(target)) errors.push(`${slug}: tool "${tool.path}" not found (or excluded from the build)`);
    }
    if (!existsSync(join(out, 'index.html'))) writeFileSync(join(out, 'index.html'), renderLauncher(app));
    continue;
  }

  const entry = app.entry ?? 'index.html';
  if (!existsSync(join(out, entry))) { errors.push(`${slug}: entry "${entry}" not found (or excluded from the build)`); continue; }

  if (entry.includes('/')) {
    // Entry lives in a subfolder: send the app URL straight to it.
    const target = `/${slug}/${dirname(entry)}/`;
    redirects.push(`/${slug} ${target} 302`, `/${slug}/ ${target} 302`);
  } else if (entry !== 'index.html') {
    // Serve the entry at /<slug>/ and keep its original file name working.
    renameSync(join(out, entry), join(out, 'index.html'));
    const old = `/${slug}/${entry}`;
    redirects.push(`${old} /${slug}/ 301`, `${old.replace(/\.html$/, '')} /${slug}/ 301`);
  }
}

for (const name of readdirSync(APPS)) {
  if (statSync(join(APPS, name)).isDirectory() && !seen.has(name)) {
    warnings.push(`apps/${name} is not listed in apps.json, so it is not deployed`);
  }
}

writeFileSync(join(DIST, 'index.html'), renderHub(readFileSync(join(SITE, 'index.html'), 'utf8')));
if (redirects.length) {
  const existing = existsSync(join(DIST, '_redirects')) ? readFileSync(join(DIST, '_redirects'), 'utf8') : '';
  writeFileSync(join(DIST, '_redirects'), `${existing}# Generated by scripts/build.mjs\n${redirects.join('\n')}\n`);
}
checkReferences();

printReport();
if (errors.length) process.exit(1);

// ---------------------------------------------------------------------------

function copyTree(from, to) {
  const stats = { files: 0, bytes: 0 };
  mkdirSync(to, { recursive: true });
  for (const item of readdirSync(from, { withFileTypes: true })) {
    const src = join(from, item.name);
    const dest = join(to, item.name);
    if (item.isDirectory()) {
      if (SKIP_DIRS.has(item.name.toLowerCase()) || item.name.startsWith('.')) continue;
      const sub = copyTree(src, dest);
      stats.files += sub.files;
      stats.bytes += sub.bytes;
    } else if (item.isFile()) {
      if (SKIP_FILES.some((re) => re.test(item.name))) continue;
      const { size } = statSync(src);
      if (size > MAX_ASSET_BYTES) { errors.push(`${rel(src)} is ${mb(size)}, over Cloudflare's 25 MiB asset limit`); continue; }
      copyFileSync(src, dest);
      stats.files += 1;
      stats.bytes += size;
    }
  }
  return stats;
}

// Fails the build when a page points at a local file that did not make it into
// dist/ (for example a file one of the skip rules removed). Files loaded from
// code (fetch, workers) only warn: apps often treat those as optional.
function checkReferences() {
  const redirected = new Set(redirects.map((line) => line.split(' ')[0]));
  const markup = /\b(?:src|href)\s*=\s*["']([^"'<>]+)["']/gi;
  const css = /url\(\s*["']?([^"')]+)["']?\s*\)/gi;
  const code = /\b(?:fetch|new Worker|importScripts)\(\s*["'`]([^"'`]+)["'`]/g;
  const checks = {
    '.html': [[markup, errors], [code, warnings]],
    '.css': [[css, errors]],
    '.js': [[code, warnings]],
  };
  for (const file of walk(DIST)) {
    for (const [re, list] of checks[extname(file).toLowerCase()] ?? []) {
      for (const [, raw] of readFileSync(file, 'utf8').matchAll(re)) {
        const ref = raw.trim().split(/[?#]/)[0];
        // Only plain relative/absolute file paths; skip URLs and minified-code noise.
        if (!/^[\w.\/%~@-]+$/.test(ref) || !/(\/|\.[a-z0-9]{1,5})$/i.test(ref) || ref.startsWith('//')) continue;
        if (!/[/]/.test(ref) && !/\.(html?|css|js|mjs|json|png|jpe?g|gif|svg|webp|ico|ttf|otf|woff2?|txt|pdf)$/i.test(ref)) continue;
        let path;
        try { path = decodeURI(ref); } catch { continue; }
        const abs = path.startsWith('/') ? join(DIST, path) : join(dirname(file), path);
        const urlPath = '/' + relative(DIST, abs).split(sep).join('/');
        if (!exists(abs) && !redirected.has(urlPath)) list.push(`${rel(file)}: missing local file "${raw}"`);
      }
    }
  }
}

function exists(abs) {
  if (existsSync(abs)) return statSync(abs).isFile() || existsSync(join(abs, 'index.html'));
  return !extname(abs) && existsSync(`${abs}.html`);
}

function* walk(dir) {
  for (const item of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, item.name);
    if (item.isDirectory()) yield* walk(path);
    else yield path;
  }
}

// --- Pages ----------------------------------------------------------------

function toolUrl(app, tool) {
  return tool.path.endsWith('.html')
    ? `/${app.slug}/${tool.path.replace(/\.html$/, '')}`
    : `/${app.slug}/${tool.path.replace(/\/$/, '')}/`;
}

function card({ href, title, description, meta }) {
  return `<li><a class="card" href="${esc(href)}">
        <span class="card-title">${esc(title)}</span>
        ${description ? `<span class="card-desc">${esc(description)}</span>` : ''}
        <span class="card-meta">${esc(meta)}</span>
      </a></li>`;
}

function renderHub(template) {
  const apps = [...config.apps].sort((a, b) => a.title.localeCompare(b.title));
  const cards = apps.map((app) => card({
    href: `/${app.slug}/`,
    title: app.title,
    description: app.description,
    meta: app.tools ? `${app.tools.length} tools` : `/${app.slug}/`,
  }));
  return template
    .replaceAll('{{title}}', esc(config.site.title))
    .replaceAll('{{tagline}}', esc(config.site.tagline))
    .replaceAll('{{count}}', String(apps.length))
    .replace('<!-- build:apps -->', cards.join('\n      '));
}

function renderLauncher(app) {
  const cards = app.tools.map((tool) => card({
    href: toolUrl(app, tool),
    title: tool.title,
    description: tool.description,
    meta: toolUrl(app, tool),
  }));
  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(app.title)} · ${esc(config.site.title)}</title>
  <meta name="robots" content="noindex">
  <link rel="icon" href="/assets/favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="/assets/hub.css">
</head>
<body>
  <main class="wrap">
    <header class="head">
      <a class="back" href="/">← All tools</a>
      <h1>${esc(app.title)}</h1>
      ${app.description ? `<p class="tagline">${esc(app.description)}</p>` : ''}
    </header>
    <ul class="grid">
      ${cards.join('\n      ')}
    </ul>
  </main>
</body>
</html>
`;
}

// --- Helpers --------------------------------------------------------------

function esc(value) {
  return String(value ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

function rel(path) {
  return relative(ROOT, path).split(sep).join('/');
}

function mb(bytes) {
  return `${(bytes / 1024 / 1024).toFixed(1)} MB`;
}

function printReport() {
  const width = Math.max(...report.map((r) => r.url.length));
  console.log(`\nBuilt dist/ with ${report.length} apps:\n`);
  for (const r of report) console.log(`  ${r.url.padEnd(width)}  ${String(r.files).padStart(4)} files  ${mb(r.bytes).padStart(8)}`);
  const total = report.reduce((sum, r) => sum + r.files, 0);
  console.log(`\n  ${total} app files, ${redirects.length} redirects`);
  for (const w of warnings) console.warn(`\nwarning: ${w}`);
  for (const e of errors) console.error(`\nerror: ${e}`);
  console.log(errors.length ? `\nBuild failed with ${errors.length} error(s).` : '\nBuild OK.');
}
