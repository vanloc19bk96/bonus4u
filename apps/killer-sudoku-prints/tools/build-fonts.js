/*
 * build-fonts.js: regenerates js/fonts.js from the TTF files in fonts/.
 *
 *   node tools/build-fonts.js          write js/fonts.js
 *   node tools/build-fonts.js --info   print names, licences and metrics only
 *
 * The app never runs this. A page opened over file:// cannot fetch() local files, so the
 * fonts travel inside a plain script as base64. The output also holds advance widths and
 * vertical metrics, so js/core/text.js measures and wraps text exactly the way both
 * renderers draw it (the SVG preview and jsPDF, both without kerning).
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const FACES = {
  serif: 'SourceSerif4-Regular.ttf',
  serifBold: 'SourceSerif4-Bold.ttf',
  sans: 'SourceSans3-Regular.ttf',
  sansBold: 'SourceSans3-Bold.ttf'
};

// Code points the layout can measure. Anything else typed by the user is replaced before
// layout (see text.js), so preview and PDF never fall back to a missing glyph.
const RANGES = [[0x20, 0x7E], [0xA0, 0x17F], [0x2010, 0x2027], [0x2030, 0x203A], [0x20AC, 0x20AC], [0x2122, 0x2122]];

function tables(buf) {
  const out = {};
  const n = buf.readUInt16BE(4);
  for (let i = 0; i < n; i++) {
    const rec = 12 + i * 16;
    out[buf.toString('latin1', rec, rec + 4)] = { offset: buf.readUInt32BE(rec + 8), length: buf.readUInt32BE(rec + 12) };
  }
  return out;
}

function nameString(buf, t, id) {
  const base = t.name.offset;
  const count = buf.readUInt16BE(base + 2);
  const strings = base + buf.readUInt16BE(base + 4);
  for (let i = 0; i < count; i++) {
    const r = base + 6 + i * 12;
    if (buf.readUInt16BE(r + 6) !== id || buf.readUInt16BE(r) !== 3) continue;
    const len = buf.readUInt16BE(r + 8), off = strings + buf.readUInt16BE(r + 10);
    let s = '';
    for (let j = 0; j < len; j += 2) s += String.fromCharCode(buf.readUInt16BE(off + j));
    return s;
  }
  return '';
}

function cmap4(buf, t) {
  const base = t.cmap.offset;
  const n = buf.readUInt16BE(base + 2);
  for (let i = 0; i < n; i++) {
    const r = base + 4 + i * 8;
    const sub = base + buf.readUInt32BE(r + 4);
    if (buf.readUInt16BE(r) !== 3 || buf.readUInt16BE(r + 2) !== 1 || buf.readUInt16BE(sub) !== 4) continue;
    const segX2 = buf.readUInt16BE(sub + 6);
    const ends = sub + 14, starts = ends + segX2 + 2, deltas = starts + segX2, ranges = deltas + segX2;
    return code => {
      for (let s = 0; s < segX2 / 2; s++) {
        const end = buf.readUInt16BE(ends + s * 2);
        if (code > end) continue;
        const start = buf.readUInt16BE(starts + s * 2);
        if (code < start) return 0;
        const delta = buf.readInt16BE(deltas + s * 2);
        const ro = buf.readUInt16BE(ranges + s * 2);
        if (ro === 0) return (code + delta) & 0xFFFF;
        const gi = buf.readUInt16BE(ranges + s * 2 + ro + (code - start) * 2);
        return gi === 0 ? 0 : (gi + delta) & 0xFFFF;
      }
      return 0;
    };
  }
  throw new Error('No Windows Unicode BMP cmap (format 4)');
}

function read(file) {
  const buf = fs.readFileSync(path.join(ROOT, 'fonts', file));
  const t = tables(buf);
  if (t.fvar) throw new Error(file + ' is a variable font; jsPDF needs static fonts');
  const upm = buf.readUInt16BE(t.head.offset + 18);
  const os2 = t['OS/2'].offset;
  const ascent = buf.readInt16BE(t.hhea.offset + 4);
  const descent = -buf.readInt16BE(t.hhea.offset + 6);
  const capHeight = buf.readUInt16BE(os2) >= 2 ? buf.readInt16BE(os2 + 88) : Math.round(upm * 0.7);
  const numH = buf.readUInt16BE(t.hhea.offset + 34);
  const glyph = cmap4(buf, t);
  const advance = gi => buf.readUInt16BE(t.hmtx.offset + Math.min(gi, numH - 1) * 4);
  const widths = {};
  RANGES.forEach(([a, b]) => {
    for (let c = a; c <= b; c++) {
      const gi = glyph(c);
      if (gi || c === 0x20) widths[c] = advance(gi);
    }
  });
  return {
    file,
    buf,
    fullName: nameString(buf, t, 4),
    copyright: nameString(buf, t, 0),
    license: nameString(buf, t, 13),
    metrics: { upm, ascent, descent, capHeight, widths }
  };
}

const faces = {};
for (const key of Object.keys(FACES)) faces[key] = read(FACES[key]);

if (process.argv.includes('--info')) {
  for (const [key, f] of Object.entries(faces)) {
    console.log(key, '|', f.fullName, '|', f.copyright);
    console.log('   upm', f.metrics.upm, 'ascent', f.metrics.ascent, 'descent', f.metrics.descent,
      'cap', f.metrics.capHeight, 'glyphs measured', Object.keys(f.metrics.widths).length);
  }
  process.exit(0);
}

let js = '/*! fonts.js: GENERATED by tools/build-fonts.js. Do not edit by hand.\n' +
  ' * Source Serif 4 and Source Sans 3, (c) Adobe, with Reserved Font Name "Source".\n' +
  ' * Licensed under the SIL Open Font License 1.1 (fonts/OFL.txt). Shipped unmodified.\n' +
  ' */\n' +
  'window.KS = window.KS || {};\n' +
  'KS.FONT_FILES = {\n';
const keys = Object.keys(faces);
keys.forEach((key, i) => {
  js += '  ' + key + ': { file: ' + JSON.stringify(faces[key].file) + ', base64: "' + faces[key].buf.toString('base64') + '" }' +
    (i < keys.length - 1 ? ',' : '') + '\n';
});
js += '};\n';
const metrics = {};
keys.forEach(key => { metrics[key] = faces[key].metrics; });
js += 'KS.FONT_METRICS = ' + JSON.stringify(metrics) + ';\n';

fs.writeFileSync(path.join(ROOT, 'js', 'fonts.js'), js);
console.log('wrote js/fonts.js (' + Math.round(js.length / 1024) + ' KB)');
