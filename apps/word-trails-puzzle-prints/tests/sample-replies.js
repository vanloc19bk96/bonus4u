function block(no, pack, count) {
  const words = pack[3].split(',').slice(0, count || 99);
  return ['PUZZLE ' + no, 'TITLE: ' + pack[0], 'THEME: ' + pack[1], 'SPAN: ' + pack[2], 'WORDS: ' + words.join(', ')].join('\n');
}

// A reply for puzzle numbers, cycling through the packs.
function reply(nos, count) {
  return '```\n' + nos.map((n) => block(n, PACKS[(n - 1) % PACKS.length], count)).join('\n\n') + '\n```';
}

