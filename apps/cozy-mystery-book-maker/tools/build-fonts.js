/*
 * Packs the bundled font files into js/fonts.js as base64 strings.
 * A page opened over file:// cannot fetch() local files, so the fonts travel inside a script.
 * The font files are shipped unmodified (SIL Open Font License; PT Serif has a Reserved Font Name).
 *
 * Usage: node tools/build-fonts.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'fonts');
const FONTS = {
  serif: 'PT_Serif-Web-Regular.ttf',
  serifBold: 'PT_Serif-Web-Bold.ttf',
  serifItalic: 'PT_Serif-Web-Italic.ttf',
  sans: 'Lato-Regular.ttf',
  sansBold: 'Lato-Bold.ttf'
};

let out = '/* Generated by tools/build-fonts.js. Do not edit.\n' +
  ' * PT Serif (c) 2010 ParaType Ltd. and Lato (c) 2010-2015 Lukasz Dziedzic.\n' +
  ' * Both are licensed under the SIL Open Font License 1.1; see the fonts folder. */\n' +
  'window.COZY_FONT_DATA = {\n';
for (const [key, file] of Object.entries(FONTS)) {
  const b64 = fs.readFileSync(path.join(SRC, file)).toString('base64');
  out += '  ' + key + ': { file: ' + JSON.stringify(file) + ', data: "' + b64 + '" },\n';
}
out += '};\n';
fs.writeFileSync(path.join(ROOT, 'js', 'fonts.js'), out);
console.log('Wrote js/fonts.js (' + Math.round(out.length / 1024) + ' KB)');
